"""Task 7 -- Conclusion."""

from __future__ import annotations

import os

from src.config import REPORT_DIR
from src.utils import banner


def main(eval_results=None):
    banner("TASK 7 -- CONCLUSION")

    summary = eval_results["summary"] if eval_results else None
    t = eval_results.get("t_stat") if eval_results else None
    p = eval_results.get("p_value") if eval_results else None

    best_row = None
    if summary is not None and len(summary):
        best_row = summary.sort_values("gain_per_hour", ascending=False).iloc[0]

    lines = [
        "# Task 7 -- Conclusion",
        "",
        "> This assignment uses simulated learners and simulated outcomes. Its metrics",
        "> do not establish learning gains, retention, or fairness for real students.",
        "",
        "## 7.1 What was built",
        "A data-driven prototype for ranking activities across subjects:",
        "",
        "1. **Content data** -- packs define subject graphs, resources, "
        "and server-graded questions.",
        "2. **Simulation** -- synthetic learners practice over generated prerequisite graphs.",
        "3. **Candidate features** -- mastery, prerequisite mastery, difficulty gap, engagement,",
        "   recent score trend, attempts, resource type, time, learner level, and learning goal.",
        "4. **Prediction and reinforcement learning** -- a score predictor and Q policy are",
        "   trained on simulated examples; the Q state/action representation is abstract.",
        "5. **Recommendation** -- predicted score, Q value, engagement, difficulty fit, and",
        "   coverage are combined after filtering resources with unmet prerequisites.",
        "6. **Evaluation** -- policy outcomes and high/low group gaps are compared in simulation.",
        "",
    ]

    if best_row is not None:
        lines += [
            "## 7.2 Headline result",
            f"The best policy by learning efficiency was **{best_row['policy']}**,",
            f"with a mean gain of **{best_row['gain']:.4f}** mastery points and",
            f"**{best_row['gain_per_hour']:.4f}** gain per hour.",
        ]
        if t is not None and p is not None and p == p:
            lines.append(
                f"A paired t-test of the hybrid optimizer against the static "
                f"curriculum gives t = {t:.3f}, p = {p:.3e}."
            )
        lines.append("")

    lines += [
        "## 7.3 Fairness",
        "* The optimizer includes a coverage term intended to avoid only-easy activities",
        "  for low-mastery or low-engagement simulated learners.",
        "* Task 6 reports simulated ability, learner-level, engagement, and mastery-group gaps.",
        "* These design choices and gaps do not guarantee fairness. The groups are",
        "  generated by the simulator, not representative demographic groups.",
        "* A short diagnostic initializes state, but the quality of its questions has",
        "  not been validated with learners or teachers.",
        "",
        "## 7.4 Limitations",
        "* Learners, scores, engagement, and mastery gains in this pipeline are simulated.",
        "* The content packs contain draft questions and resource labels, not reviewed",
        "  teaching materials or a real hosted resource library.",
        "* The tabular Q policy discretizes mastery, difficulty gap, engagement, and",
        "  prerequisite readiness; this loses detail from continuous learner state.",
        "* A model trained on generated graphs may not generalize to real topics or people.",
        "* Public teacher self-registration is a security and content-integrity risk.",
        "* Database concurrency, production deployment, accessibility, and privacy",
        "  practices need further validation.",
        "",
        "## 7.5 Practical implementation notes",
        "* The server caches available model artifacts in process memory and uses a",
        "  prerequisite-aware ZPD fallback if the predictor or Q table is unavailable",
        "  or incompatible.",
        "* The API grades submitted answers on the server; the browser does not receive",
        "  correct answer indexes in quiz question responses.",
        "* Activity duration is client-reported. Do not interpret it as verified time-on-task.",
        "* Before deployment, restrict teacher account creation, review content, assess",
        "  privacy and consent, and test concurrency and recovery.",
        "",
        "## 7.6 Future scope",
        "* Copy trusted generalized model artifacts from a reviewed training run into the local "
        "outputs only when they are intended for deployment.",
        "* Have teachers review and improve the content packs and diagnostic items.",
        "* Evaluate with real learners only under an approved, consented research plan.",
        "* Add secure teacher provisioning, audit logs, operational backups, and",
        "  deployment-grade database support.",
        "* Validate accessibility, recommendation explanations, and group outcomes.",
        "",
        "## 7.7 Final takeaway",
        "This is a working prototype for exploring subject-agnostic adaptive",
        "recommendations. Simulated results can help test software behavior and",
        "compare policies inside the chosen simulator. They cannot show that the",
        "system improves real learning or is ready for classroom deployment.",
    ]

    report_path = os.path.join(REPORT_DIR, "task7_conclusion.md")
    with open(report_path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))

    print("\n".join(lines[:40]))
    print(f"\n[task7] report -> {report_path}")
    return report_path


if __name__ == "__main__":
    main()
